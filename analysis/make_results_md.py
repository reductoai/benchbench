"""Generate docs/RESULTS.md from saved numeric results without API calls."""

import argparse
import json
import statistics
from pathlib import Path

from headlines import summarize

ROOT = Path(__file__).resolve().parents[1]


def winners(vendors, key):
    top = max(v[key] for v in vendors)
    return sorted(v["vendor"] for v in vendors if v[key] == top)


def repeat_winners(check, ids):
    groups = {row["id"]: row for row in check["benchmarks"]}
    if set(groups) != set(ids):
        raise ValueError("Incomplete repeat cohort")
    count = 0
    for row in groups.values():
        tops = row["winners"]
        if row["pages"] <= 0 or len(tops) != 2 or not all(tops):
            raise ValueError(f"Incomplete repeat cohort: {row['id']}")
        count += tops[0] == tops[1]
    return count


def render(data):
    summary = summarize(data)
    benchmarks = data["benchmarks"]
    leads = {}
    for b in benchmarks:
        scores = sorted((v["native_clean"] for v in b["vendors"]), reverse=True)
        loss = statistics.median(v["native_clean"] - v["native_tilt"] for v in b["vendors"])
        leads[b["id"]] = (scores[0] - scores[1], loss)
    lines = [
        "# Results",
        "",
        "Generated by `python analysis/make_results_md.py`. Do not edit by hand.",
        "",
        "## Cohort summary",
        "",
        "The study covers 12 benchmarks and 96 parser-benchmark pairs. Each benchmark has equal weight.",
        "",
        "| Measure | 12 benchmarks |",
        "|---|---:|",
    ]
    for metric, label in (("native", "Native"), ("gpt", "PAIR")):
        lines.append(f"| {label} winner changes after tilt | {len(summary[metric]['winner_changes'])}/12 |")
        lines.append(f"| Median {label} relative tilt loss | {summary[metric]['median_drop_pct']:.1f}% |")
    repeats = data.get("refresh", {}).get("repeat_check")
    lead = summary["leads_smaller_pct"]
    lines.append(f"| Native percentage lead smaller than median percentage tilt loss | {lead}/12 |")
    if repeats is not None:
        agree = repeat_winners(repeats, summary["benchmarks"])
        lines.append(f"| PAIR clean repeat winner agreement | {agree}/12 |")
    lines += [
        "",
        "Sources: `results/data.json` and `analysis/headlines.py`.",
        "Repeat agreement compares refreshed Sol r0 and r1 winners on matched complete clean pages.",
        "",
        "Relative loss is `100 * (1 - tilt / clean)`, with the median over benchmark-preset cells.",
        "A negative loss is a gain. The native lead is best minus second-best clean native score.",
        "As a percentage, the lead is `100 * (best - second) / best`. It is compared with",
        "the median parser's percentage tilt loss within the benchmark. Winner changes compare",
        "exact top-score sets, including ties. The raw-score-point variant is shown separately below.",
        "Calculations use stored numeric precision, without rounding first. Native scores are on",
        "a 0-100 scale; PAIR is on a 1-10 scale.",
        "",
        "## Per-benchmark winners",
        "",
        "Source: `results/data.json`. Primary PAIR averages clean r0 and r1; tilt uses r0.",
        "The tilt judge sees the clean reference image.",
        "See the methodology for failure handling and scorer aggregation.",
        "",
        "| Benchmark ID | Native clean | Native tilt | PAIR clean | PAIR tilt |",
        "|---|---|---|---|---|",
    ]
    for b in benchmarks:
        cells = [
            ", ".join(winners(b["vendors"], key))
            for key in ("native_clean", "native_tilt", "gpt_clean", "gpt_tilt")
        ]
        lines.append(f"| `{b['id']}` | {' | '.join(cells)} |")
    lines += [
        "",
        "## Native leads and tilt loss",
        "",
        "Source: `results/data.json`. Both sides of the headline comparison are percentages.",
        "IDP's lead is 11.8% versus a median tilt loss of 13.4%.",
        "The separate raw-score-point definition gives 8/12 rather than 9/12.",
        "",
        "| Benchmark ID | Lead % | Median loss % | Lead smaller? | Lead points | Median loss points |",
        "|---|---:|---:|---|---:|---:|",
    ]
    for b in benchmarks:
        lead, loss = leads[b["id"]]
        pct = summary["native_leads"][b["id"]]
        lp, dp = pct["lead_pct"], pct["median_loss_pct"]
        lines.append(
            f"| `{b['id']}` | {lp:.4f} | {dp:.4f} | {'yes' if lp < dp else 'no'} | {lead:.4f} | {loss:.4f} |"
        )
    ablations = data.get("refresh", {}).get("judge_ablations")
    if ablations:
        lines += [
            "",
            "## Judge checks",
            "",
            "Same-winner comparisons use matched complete pages against Sol clean r0+r1 and tilt r0.",
            "",
            "| Judge | Condition | Same winner as Sol | Reducto first | Matched/Sol pages | ok:false |",
            "|---|---|---:|---:|---:|---:|",
        ]
        for row in ablations:
            lines.append(
                f"| {row['judge']} | {row['condition']} | {row['same_winner']}/{row['benchmarks']} "
                f"| {row['reducto_first']}/{row['benchmarks']} "
                f"| {row['matched_pages']}/{row['sol_pages']} | {row['failed_pages']} |"
            )
        lines += [
            "",
            "[Appendix](../results/appendix/) includes winners, rank correlations, failures and 90%",
            "percentile bootstrap intervals (2,000 paired page resamples, seed 0).",
            "Relative changes use `100 * (tilt / clean - 1)` on pages complete in both conditions.",
        ]
    lines += [
        "",
        "## Per-vendor scores",
        "",
        "Source: `results/data.json`. Display values are rounded to four decimals; ranks are",
        "computed before display rounding, with competition ranks (1, 2, 2, 4). The saved",
        "`pages` field counts primary clean judged pages, not necessarily sampled pages.",
        "Sample counts are in `results/samples/<id>/pages.jsonl`.",
    ]
    for b in benchmarks:
        lines += [
            "",
            f"### {b['name']} (`{b['id']}`)",
            "",
            f"Native metric: {b['metric']}. Primary clean judged pages: {b['pages']}.",
            "",
            "| Vendor | Preset | Native clean (rank) | Native tilt (rank) | PAIR clean (rank) | PAIR tilt (rank) |",  # noqa: E501
            "|---|---|---:|---:|---:|---:|",
        ]
        for v in b["vendors"]:
            cells = []
            for key in ("native_clean", "native_tilt", "gpt_clean", "gpt_tilt"):
                rank = 1 + sum(x[key] > v[key] for x in b["vendors"])
                cells.append(f"{v[key]:.4f} ({rank})")
            lines.append(f"| {v['vendor']} | `{v['preset']}` | {' | '.join(cells)} |")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results", type=Path, default=ROOT / "results")
    parser.add_argument("--output", type=Path, default=ROOT / "docs/RESULTS.md")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = json.loads((args.results / "data.json").read_text())
    output = render(data)
    if args.check:
        if args.output.read_bytes() != output.encode():
            raise SystemExit(f"OUT OF DATE: {args.output}")
        print("docs/RESULTS.md is byte-identical")
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(output, encoding="utf-8")
        print("Wrote docs/RESULTS.md")


if __name__ == "__main__":
    main()
